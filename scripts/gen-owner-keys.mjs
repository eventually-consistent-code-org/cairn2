#!/usr/bin/env node

// Owner-only key list generator (#281).
//
// The server is the source of the list of cairn.json keys only the owner
// sets (server/src/config.ts: OWNER_ONLY_KEYS, and OWNER_ONLY_SAFE, the one
// value each may be set to without the owner). The hooks import no server
// code (#391), so the harness guard reads a generated copy instead:
// hooks/scripts/owner-keys.mjs, which this script writes. The list is read
// off the BUILT server (server/dist/config.js) in a child process -- never
// an import of server code from the plugin layer -- so run
// `cd server && npm run build` first; check-dist already demands a fresh
// dist. `--check` writes nothing and exits 1 when the copy on disk differs.
//
// The parity test (server/test/config.test.ts, "owner-only keys") renders
// the SOURCE's list through the same `render` and holds the copy to it byte
// for byte, so a copy generated from a stale dist fails there, by name.
// An empty list is refused here: a copy that protects nothing is not a
// copy, it is a failure that looks like a pass.

import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Where the copy lives: beside the harness guard, which imports it as a sibling. */
export const OUT = join(root, "hooks", "scripts", "owner-keys.mjs");

/**
 * The generated module's text for a key list and its safe values -- one
 * shape for the generator and the parity test, so the test can render the
 * source's own list and compare bytes.
 */
export function render(keys, safe) {
  if (!Array.isArray(keys) || !keys.length) throw new Error("gen-owner-keys: an empty key list is a failure, not a pass");
  const keyLines = keys.map((k) => `  ${JSON.stringify(k)},`).join("\n");
  const safeLines = keys.filter((k) => Object.hasOwn(safe ?? {}, k))
    .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(safe[k])},`).join("\n");
  return `#!/usr/bin/env node

/**
 * Purpose: the cairn.json keys only the owner sets (#281), copied from the
 *   server's list -- server/src/config.ts OWNER_ONLY_KEYS, and OWNER_ONLY_SAFE,
 *   the one value each may be set to without the owner -- for the harness
 *   guard to read: hooks import no server code (#391), so this is a
 *   generated copy, and server/test/config.test.ts "owner-only keys" fails
 *   when the two drift. A key with no safe value (the write table) is the
 *   owner's whatever is written.
 *
 *   Generated by scripts/gen-owner-keys.mjs -- regenerate, never hand-edit.
 * derives: axiom 5 (owner-ground)
 * Author(s): John Reed
 */

export const OWNER_ONLY_KEYS = Object.freeze([
${keyLines}
]);

export const OWNER_ONLY_SAFE = Object.freeze({
${safeLines}
});
`;
}

/** The list as the built server exports it, asked of server/dist/config.js in a child process. */
export function readKeys() {
  const dist = join(root, "server", "dist", "config.js");
  const probe = `import(${JSON.stringify(pathToFileURL(dist).href)}).then((m) => ` +
    "process.stdout.write(JSON.stringify({ keys: m.OWNER_ONLY_KEYS, safe: m.OWNER_ONLY_SAFE })))";
  const r = spawnSync(process.execPath, ["--input-type=module", "-e", probe], { encoding: "utf8", timeout: 20000 });
  if (r.status !== 0) {
    throw new Error(`gen-owner-keys: could not read server/dist/config.js -- run \`cd server && npm run build\` first\n${r.stderr}`);
  }
  const { keys, safe } = JSON.parse(r.stdout);
  if (!Array.isArray(keys) || !keys.length) throw new Error("gen-owner-keys: the server exported no owner-only keys -- an empty list is a failure, not a pass");
  return { keys, safe: safe ?? {} };
}

// Main -- only when run as a command; the parity test imports `render` alone.
const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const check = process.argv.includes("--check");
  const { keys, safe } = readKeys();
  const text = render(keys, safe);
  let current = null;
  try { current = readFileSync(OUT, "utf8"); } catch { /* not written yet */ }
  if (check) {
    if (current === text) {
      console.log(`gen-owner-keys: clean — ${keys.length} owner-only keys, hooks/scripts/owner-keys.mjs matches the server`);
      process.exit(0);
    }
    console.error("gen-owner-keys: hooks/scripts/owner-keys.mjs differs from the server's list — run `node scripts/gen-owner-keys.mjs`");
    process.exit(1);
  }
  writeFileSync(OUT, text);
  console.log(`owner-only keys written: ${keys.length} keys -> hooks/scripts/owner-keys.mjs`);
}
